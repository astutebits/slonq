#[tokio::test]
async fn test_ack_batch() -> Result<(), Box<dyn std::error::Error>> {
    let (queue, _node) = setup_db().await;

    queue.enqueue("k1", json!(1), 10, None).await?;
    queue.enqueue("k2", json!(2), 10, None).await?;

    let jobs = queue.dequeue("w1", 10, 3).await?;
    assert_eq!(jobs.len(), 2);

    let leases: Vec<_> = jobs.iter().map(|j| j.lease_key().unwrap()).collect();
    let acked = queue.ack_batch(&leases).await?;
    assert_eq!(acked.len(), 2);
    assert!(acked.iter().all(|j| j.status == JobStatus::Done));

    Ok(())
}

#[tokio::test]
async fn test_nack_with_delay() -> Result<(), Box<dyn std::error::Error>> {
    use std::time::Duration;
    let (queue, _node) = setup_db().await;

    queue.enqueue("k1", json!(1), 10, None).await?;
    let jobs = queue.dequeue("w1", 1, 3).await?;
    let lease = jobs[0].lease_key().unwrap();

    // Nack with a one-hour delay
    let nacked = queue
        .nack(lease, 3, Some(Duration::from_secs(3600)))
        .await?
        .expect("Should have Job");
    assert!(nacked.visible_at > Utc::now() + Duration::from_secs(3500));

    // Should not be able to dequeue immediately
    let jobs2 = queue.dequeue("w2", 1, 3).await.unwrap();
    assert!(jobs2.is_empty());

    Ok(())
}
