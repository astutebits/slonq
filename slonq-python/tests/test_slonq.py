@pytest.mark.asyncio
async def test_touch_lease(queue):
    key = "k1-" + str(uuid.uuid4())
    await queue.enqueue(key, 1, 10)
    jobs = await queue.dequeue("w1", 1, 3)
    lease = jobs[0].lease_key()
    assert lease is not None

    touched = await queue.touch(lease, 30)
    assert touched is not None
    
    visible_at_orig = parse_rfc3339(jobs[0].visible_at)
    visible_at_touched = parse_rfc3339(touched.visible_at)
    assert visible_at_touched > visible_at_orig

@pytest.mark.asyncio
async def test_nack_with_delay(queue):
    key = "k1-" + str(uuid.uuid4())
    await queue.enqueue(key, 1, 10)
    jobs = await queue.dequeue("w1", 1, 3)
    lease = jobs[0].lease_key()
    assert lease is not None

    # Nack with a one-hour delay (3600 seconds)
    nacked = await queue.nack(lease, 3, delay_seconds=3600.0)
    assert nacked is not None
    
    visible_at = parse_rfc3339(nacked.visible_at)
    now = datetime.datetime.now(datetime.timezone.utc)
    assert visible_at > now + datetime.timedelta(seconds=3500)

    # Should not be able to dequeue immediately
    jobs2 = await queue.dequeue("w2", 1, 3)
    assert len(jobs2) == 0

@pytest.mark.asyncio
async def test_ack_batch(queue):
    k1 = "k1-" + str(uuid.uuid4())
    k2 = "k2-" + str(uuid.uuid4())
    await queue.enqueue(k1, 1, 10)
    await queue.enqueue(k2, 2, 10)

    jobs = await queue.dequeue("w1", 10, 3)
    assert len(jobs) == 2

    leases = [j.lease_key() for j in jobs]
    acked = await queue.ack_batch(leases)
    assert len(acked) == 2
    assert all(j.status == JobStatus.Done for j in acked)
